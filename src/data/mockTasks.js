// Helper: get tasks by project
export const getTasksByProject = (projectId) =>
  mockTasks.filter((t) => t.projectId === projectId && !t.parentTaskId)

// Helper: get subtasks of a task
export const getSubtasks = (parentTaskId) =>
  mockTasks.filter((t) => t.parentTaskId === parentTaskId)

// Helper: get tasks due today
export const getTodayTasks = () => {
  const todayStr = fmt(new Date())
  return mockTasks.filter((t) => t.dueDate === todayStr && !t.parentTaskId)
}

// Helper: get overdue tasks
export const getOverdueTasks = () => {
  const todayStr = fmt(new Date())
  return mockTasks.filter(
    (t) => t.dueDate && t.dueDate < todayStr && !t.completed && !t.parentTaskId
  )
}
